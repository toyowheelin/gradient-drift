"""
check_plugin_policy.py - verifies the C# plugin's learned-policy hook against a real server run.

Run a test with EnableLearnedPolicy: true (and LogLearnedPolicyObservations left on), then:

    python check_plugin_policy.py drift_physics_telemetry_<date>_<time>.csv
    python check_plugin_policy.py <telemetry.csv> --policy runs/<name>/policy.json

Three questions, in order:

  1. Is the C# network the same network?  Every logged PolicyObs row is replayed through the
     Python copy of the policy and the resulting actions compared with the logged
     PolicySteerAction / PolicySpeedAction.
  2. Is the C# feeding it the right inputs?  Individual observation slots are re-derived from the
     OTHER telemetry columns (cross-track error, tick length, last tick's rays/pins/yaw rate/
     steering, the spline lookahead ...) and compared. A wrong slot, scale or one-tick lag shows
     up here as a specific failing line.
  3. Does the car do on the server what it does in the simulator?  The simulator drives the same
     policy for the same number of ticks, with the same car speed limit and NO resets (the
     server never resets a lost car either), 128 times over; the server run's drift time, wall
     contact, time off the track etc. are shown against the spread of those runs.
     (--no-sim skips this part; replay_live.py goes further and compares tick by tick.)

    python check_plugin_policy.py --self-test     # runs the checks on telemetry generated by the
                                                  # simulator itself (no server needed)
"""
