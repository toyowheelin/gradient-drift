MAX_STEER_DEG = 28.125      # the plugin's default; a policy file may carry its own (see max_steer)


def wrap_deg(x):
    return (x + 180.0) % 360.0 - 180.0


def load_telemetry(path):
    import pandas as pd
    df = pd.read_csv(path, on_bad_lines='skip', low_memory=False, dtype={'PolicyObs': str, 'RayDistances': str,
                                                                        'PinDistances': str})
    if 'PolicyObs' not in df.columns:
        sys.exit("This telemetry has no PolicyObs column - it was written by a build without the learned-"
                 "policy hook (rebuild and redeploy the plugin, then run the test again).")
    for c in df.columns:
        if df[c].dtype == object and c not in ('PolicyObs', 'RayDistances', 'RaySurfaces', 'PinDistances', 'PinSurfaces'):
            vals = df[c].astype(str).str.strip()
            if vals.isin(['True', 'False', 'nan']).all():
                df[c] = vals == 'True'
            else:
                df[c] = pd.to_numeric(df[c], errors='coerce')
    # a killed server leaves the last row cut off mid-field: drop rows whose final column is missing
    df = df.dropna(subset=['Tick', 'SessionId', 'SpawnCounter', 'PolicySpeedAction'])
    # SessionId 255: a row the plugin writes for the human car alone, when no AI car is out
    df = df[df.SessionId != 255]
    # a tandem-train follower's row (FollowLeadId >= 0): it replays its lead, no policy of its own
    if 'FollowLeadId' in df.columns:
        df = df[~(df.FollowLeadId >= 0)]
    # The direct-only plugin writes a shorter file: the columns of the removed
    # hand-written controller are gone and the one recovery flag left is called what it is.
    # The older name is kept as an alias so the rest of this tool reads either format.
    if 'UncontrolledSpinRecovering' not in df.columns and 'WrongWayRecovering' in df.columns:
        df['UncontrolledSpinRecovering'] = df['WrongWayRecovering']
    return df.sort_values(['SessionId', 'SpawnCounter', 'Tick']).reset_index(drop=True)


def plugin_overrides_for(df):
    """fast_sim.PLUGIN_CONFIG_OVERRIDES matching the plugin build that wrote this telemetry.
    The ground-ray height announces itself through its GroundRayUsed column: a file
    without the column, or with it False throughout, came from a plugin using the older
    spline/road-mesh height, and the simulator has to do the same to be comparable."""
    ground_ray = 'GroundRayUsed' in df.columns and bool(df['GroundRayUsed'].fillna(False).astype(bool).mean() > 0.5)
    return {'EXT_GROUND_RAY_HEIGHT': 1.0 if ground_ray else 0.0}


def pace_over_from_telemetry(df, world, fs, average_s):
    """Per telemetry row, the pace error the network should have seen that tick: worked out from
    the same car's earlier rows (positions after each tick, tick lengths, paces, nearest points),
    as drift_env._step_one keeps counters 8 and 9. NaN where the car's rows do not go back to its
    first tick."""
    out = np.full(len(df), np.nan)
    lap = float(world.sp_cum[-1] + world.sp_length[-1])
    keys = df['SessionId'].astype(str) + '/' + df['SpawnCounter'].astype(str)
    for _, rows in df.groupby(keys, sort=False):
        rows = rows.sort_values('Tick')
        arc_prev, avg_speed, avg_asked, ticks, last_tick, value = np.nan, 0.0, 0.0, 0, None, 0.0
        for idx, r in zip(rows.index, rows.itertuples()):
            if last_tick is not None and r.Tick != last_tick + 1:
                ticks, value = -1, np.nan        # a gap: the history is lost
            last_tick = r.Tick
            if ticks >= 0:
                out[idx] = value
            x, y, z = float(r.PosX), float(r.PosY), float(r.PosZ)
            na = fs.world_to_spline(x, y, z, world.sp_pos)
            a, _, t = fs.find_interpolation_segment(x, y, z, na, world.sp_pos, world.sp_next, world.sp_prev)
            arc = world.sp_cum[a] + t * world.sp_length[a]
            progress = 0.0 if np.isnan(arc_prev) else arc - arc_prev
            if progress > lap / 2:
                progress -= lap
            elif progress < -lap / 2:
                progress += lap
            arc_prev = arc
            point = int(r.NearestPointId)
            if ticks < 0 or point < 0:          # -1: the stock AI had the car stopped
                continue
            dt = max(float(r.RealDtMs) / 1000.0, 1e-3)
            speed = min(5.0, max(-2.0, progress)) / dt
            asked = float(r.Pace) * min(world.pace_ref[min(point, len(world.pace_ref) - 1)], float(r.CeilingKmh)) / 3.6
            if ticks == 0:
                avg_speed, avg_asked = speed, asked
            else:
                k = min(1.0, dt / max(average_s, 1e-3))
                avg_speed += (speed - avg_speed) * k
                avg_asked += (asked - avg_asked) * k
            ticks += 1
            value = avg_speed / avg_asked - 1.0 if asked > 0.0 and avg_asked > 0.5 else 0.0
    return out


def parse_vectors(series, width):
    out = np.full((len(series), width), np.nan)
    for i, s in enumerate(series):
        if isinstance(s, str) and s:
            parts = s.split(';')
            if 0 < len(parts) <= width:          # a file from before inputs were added has fewer
                try:
                    out[i, :len(parts)] = [float(p) for p in parts]
                except ValueError:
                    pass
    return out


class Report:
    def __init__(self):
        self.failed = 0

    def line(self, name, got, want, tol, min_pass=0.98, unit=''):
        got, want = np.asarray(got, dtype=float), np.asarray(want, dtype=float)
        ok = np.isfinite(got) & np.isfinite(want)
        if ok.sum() == 0:
            print(f"  {'SKIP':5s} {name:44s} nothing to compare")
            return
        err = np.abs(got[ok] - want[ok])
        frac = float((err <= tol).mean())
        passed = frac >= min_pass
        self.failed += 0 if passed else 1
        print(f"  {'PASS' if passed else 'FAIL':5s} {name:44s} n={ok.sum():6d}  median err {np.median(err):8.4f}{unit}  "
              f"p99 {np.quantile(err, 0.99):8.4f}{unit}  within {tol:g}{unit}: {frac:6.1%}")


def run_checks(df, policy, world, de, fs, simulate=True):
    rep = Report()
    obs_all = parse_vectors(df['PolicyObs'], de.OBS_SIZE)
    # the inputs this policy reads (a build from before inputs were added logs fewer)
    has_obs = np.isfinite(obs_all[:, :len(policy.obs_mean)]).all(axis=1)
    active = df['PolicyActive'].to_numpy(dtype=bool) & has_obs
    n_rows = len(df)
    print(f"\n{n_rows} telemetry rows, {int(df['PolicyActive'].sum())} with the policy active, "
          f"{int(has_obs.sum())} with a logged observation")
    if active.sum() == 0:
        print("\nThe policy never ran. Check the server log for a 'learned policy' line: it says whether "
              "the file loaded, and if not, why. (EnableLearnedPolicy must be true in extra_cfg.yml.)")
        return 1
    d = df[active].reset_index(drop=True)
    obs = obs_all[active]

    # previous tick of the same car (Tick is the plugin's global tick counter)
    prev = df.shift(1)
    consecutive = ((df['SessionId'] == prev['SessionId']) & (df['SpawnCounter'] == prev['SpawnCounter'])
                   & (df['Tick'] - prev['Tick'] == 1)).to_numpy()
    p = prev[active].reset_index(drop=True)
    has_prev = consecutive[active] & (obs[:, 45] < 0.5)
    nan = np.nan

    def prev_col(name):
        return np.where(has_prev, p[name].to_numpy(dtype=float), nan)

    print("\n1. Is it the same network?  (logged observation -> Python policy -> compare actions)")
    act = policy(obs)
    # Below full skill (input 66, the plugin's BotSkill) the plugin hands the car what the network
    # asked a tick or two earlier, plus a wandering noise on steering and pedal (HandicapBySkill,
    # drift_env._step_one): the brake must then match the delayed action exactly, and what is left
    # of steering and pedal must look like that noise.
    skill = float(np.nanmedian(obs[:, de.SKILL_OBS_SLOT])) if len(policy.obs_mean) > de.SKILL_OBS_SLOT else 1.0
    lack = 1.0 - min(1.0, max(0.0, skill))
    delay = int(de.SKILL_DELAY_TICKS * lack + 0.5)
    if lack > 0:
        print(f"  (skill {skill:.2f}: actions reach the car {delay} tick(s) late, with steering/pedal noise)")
        full = np.full((n_rows, act.shape[1]), np.nan)
        full[active] = act
        chain = active.copy()
        for _ in range(delay):
            full = np.roll(full, 1, axis=0)
            chain = np.roll(chain, 1) & consecutive & (obs_all[:, 45] < 0.5)
            full[~chain] = np.nan
        act = full[active]
    if lack > 0:
        for j, (col, amp) in enumerate((('PolicySteerAction', de.SKILL_STEER_NOISE), ('PolicySpeedAction', de.SKILL_PEDAL_NOISE))):
            r = d[col].to_numpy(dtype=float) - act[:, j]
            r = np.where(np.abs(act[:, j]) < 1.0 - 3 * amp * lack, r, np.nan)   # not where the clamp bites
            ok = np.isfinite(r)
            pairs = ok[1:] & ok[:-1]
            std, want = float(np.std(r[ok])), amp * lack
            ac = float(np.corrcoef(r[1:][pairs], r[:-1][pairs])[0, 1])
            passed = abs(std / want - 1.0) < 0.25 and ac > 0.75
            rep.failed += 0 if passed else 1
            print(f"  {'PASS' if passed else 'FAIL':5s} {col[6:11].lower() + ' action (delayed) + skill noise':44s} n={ok.sum():6d}  "
                  f"noise std {std:.3f} (expected {want:.3f})  tick-to-tick correlation {ac:.2f} (expected {de.SKILL_NOISE_KEEP})")
    else:
        rep.line('steer action', act[:, 0], d['PolicySteerAction'], 0.02, 0.995)
        rep.line('speed action', act[:, 1], d['PolicySpeedAction'], 0.02, 0.995)
    if act.shape[1] > 2:
        if 'PolicyBrakeAction' in d:
            rep.line('brake action' + (' (delayed)' if delay else ''), np.clip(act[:, 2], 0.0, 1.0),
                     d['PolicyBrakeAction'], 0.02, 0.995)
        else:
            print("  SKIP  brake action: this telemetry has no PolicyBrakeAction column (a build from before the brake)")

    print("\n2. Are the inputs right?  (observation slot vs the telemetry column it should equal)")
    # the steering lock the policy was trained with (its file says so when it is not the plugin's default)
    max_steer = de.max_steer_deg(policy.meta)
    if abs(max_steer - MAX_STEER_DEG) > 1e-9:
        print(f"  (steering lock from the policy file: {max_steer:g} deg)")
    rep.line('[5]  cross-track error, m', obs[:, 5] * 15.0, np.clip(d['CrossTrackErrorM'], -45, 45), 0.02, unit=' m')
    rep.line('[39] tick length, ms', obs[:, 39] * 100.0, d['RealDtMs'], 0.11, unit=' ms')
    de.require_direct(policy.meta)
    # Slot 35 carries (1 - RearSlidingGrip) / 0.5, zero for a policy trained without that
    # setting; it has to be one value for the whole run and inside the range the policy was
    # trained over. Slot 36 is always zero.
    grip = 1.0 - 0.5 * obs[:, 35]
    sliding_grip = float(np.nanmedian(grip))
    grip_low, grip_high = de.sliding_grip_range(policy.meta)
    rep.line(f'[35] rear sliding grip, constant at {sliding_grip:.3f}', grip, np.full(len(d), sliding_grip), 1e-5)
    rep.line(f'[35] rear sliding grip inside the trained {grip_low:g} - {grip_high:g}', grip,
             np.clip(grip, grip_low, grip_high), 1e-5)
    rep.line('[36] always 0', obs[:, 36], np.zeros(len(d)), 1e-6)
    rep.line('[12] max speed, km/h', obs[:, 12] * 25.0 * 3.6, d['CeilingKmh'], 0.11, unit=' km/h')
    rep.line('[1]  lateral velocity (last tick), m/s', obs[:, 1] * 10.0, prev_col('LateralVelocityMs'), 0.005, unit=' m/s')
    rep.line('[2]  yaw rate (last tick), deg/s', np.degrees(obs[:, 2] * 2.0), prev_col('YawRateDegS'), 0.05, unit=' deg/s')
    rep.line('[41] steering command (last tick), deg', obs[:, 41] * max_steer, prev_col('SteerCommandDeg'), 0.03, unit=' deg')
    rep.line('[37] previous steer action', obs[:, 37], prev_col('PolicySteerAction'), 0.002)
    rep.line('[38] previous speed action', obs[:, 38], prev_col('PolicySpeedAction'), 0.002)
    if len(policy.obs_mean) > de.PACE_OBS_SLOT:
        # the pace and the brake inputs (a policy trained with them)
        # a fraction of the course's flat-out speed; gen4 policies: km/h / 50
        fraction = 'pace_fraction_range' in policy.meta
        pace_low, pace_high = (de.pace_range(policy.meta) if fraction
                               else tuple(policy.meta.get('pace_kmh_range') or (0.0, 0.0)))
        unit = '' if fraction else ' km/h'
        pace = obs[:, de.PACE_OBS_SLOT] * (1.0 if fraction else 50.0)
        if 'Pace' in d:
            rep.line(f'[{de.PACE_OBS_SLOT}] pace', pace, d['Pace'], 0.0002 if fraction else 0.01, unit=unit)
        rep.line(f'[{de.PACE_OBS_SLOT}] pace inside the trained {pace_low:g} - {pace_high:g}{unit}', pace,
                 np.clip(pace, pace_low, pace_high), 1e-3, unit=unit)
        if 'PolicyBrakeAction' in d:
            rep.line(f'[{de.PACE_OBS_SLOT + 1}] previous brake action', obs[:, de.PACE_OBS_SLOT + 1],
                     prev_col('PolicyBrakeAction'), 0.002)
    if len(policy.obs_mean) > de.PACE_OVER_SLOT:
        # the pace error: what the plugin logged, and the same worked out here from the car's
        # logged positions, ticks and paces the way drift_env keeps it
        got = obs[:, de.PACE_OVER_SLOT]
        if 'PaceOver' in d:
            rep.line(f'[{de.PACE_OVER_SLOT}] pace error = the PaceOver column', got,
                     np.clip(d['PaceOver'].to_numpy(dtype=float), -de.PACE_OVER_CLIP, de.PACE_OVER_CLIP), 0.0002)
        if getattr(world, 'pace_ref', None) is not None:
            want = pace_over_from_telemetry(df, world, fs, float(policy.meta.get('pace_average_s', 1.0)))[active]
            if 'PaceOver' in d:
                # each car is asked its PACE_SCALE times the reference speed (its car file, not in the
                # telemetry): read it back as the steady ratio of the two, rounded as car files carry it
                logged = d['PaceOver'].to_numpy(dtype=float)
                keys = (d['SessionId'].astype(str) + '/' + d['SpawnCounter'].astype(str)).to_numpy()
                scales = []
                for k in dict.fromkeys(keys):
                    m = (keys == k) & np.isfinite(want) & (np.abs(want) > 1e-6) & (np.abs(logged) < de.PACE_OVER_CLIP)
                    if m.sum() > 50:
                        s = round(float(np.median((1.0 + want[m]) / (1.0 + logged[m]))), 4)
                        want[keys == k] = (1.0 + want[keys == k]) / s - 1.0
                        scales.append(s)
                print(f"        cars' pace scales the plugin used: {', '.join(f'{s:g}' for s in scales)}")
            rep.line(f'[{de.PACE_OVER_SLOT}] pace error worked out from positions', got,
                     np.clip(want, -de.PACE_OVER_CLIP, de.PACE_OVER_CLIP), 0.01, 0.97)
        else:
            print(f"  SKIP  [{de.PACE_OVER_SLOT}] pace error from positions: no <track>_pace_reference.csv in the track's folder")
    own_prev = np.sqrt(np.maximum(prev_col('SpeedKmh') ** 2 - (prev_col('LateralVelocityMs') * 3.6) ** 2, 0.0))
    rep.line('[0]  own speed (last tick), km/h', obs[:, 0] * 25.0 * 3.6, own_prev, 1.5, 0.95, unit=' km/h')
    rays_prev = parse_vectors(p['RayDistances'], de.N_RAYS)
    pins_prev = parse_vectors(p['PinDistances'], de.N_PINS)
    rays_prev[~has_prev] = nan
    pins_prev[~has_prev] = nan
    rep.line('[13-27] fan distances (last tick), m', (obs[:, 13:28] * 60.0).ravel(), rays_prev.ravel(), 0.06, unit=' m')
    rep.line('[29-34] pin distances (last tick), m', (obs[:, 29:35] * 12.0).ravel(), pins_prev.ravel(), 0.06, unit=' m')
    fan_rel = wrap_deg(prev_col('FanCenterDeg') - prev_col('RealHeadingDeg'))
    rep.line('[28] fan centre vs heading, deg', obs[:, 28] * 180.0, fan_rel, 0.15, unit=' deg')
    target = np.degrees(d['CorrectedSplineAngle'].to_numpy(dtype=float))
    ad = wrap_deg(target - prev_col('RealHeadingDeg'))
    rep.line('[4]  angle to the racing line, deg', wrap_deg(obs[:, 4] * 180.0 - ad), np.zeros(len(d)), 0.2, unit=' deg')
    if 'UncontrolledSpinRecovering' in df.columns:
        # the flag in the observation is the STATE left by the last tick; the telemetry column is
        # "was recovering during that tick", which differs on the one tick a recovery ends
        rep.line('[40] spin-recovery flag (last tick)', obs[:, 40], np.where(has_prev, p['UncontrolledSpinRecovering'].to_numpy(dtype=float), nan), 0.5, 0.97)

    # spline lookahead: nearest point from where the tick STARTED (the previous row's position)
    sp_dir, la_idx, la_minr = de.spline_lookahead_tables(world)
    px, py, pz = prev_col('PosX'), prev_col('PosY'), prev_col('PosZ')
    look = np.full((len(d), de.N_LOOK), nan)
    minr = np.full(len(d), nan)
    corr = d['CorrectedSplineAngle'].to_numpy(dtype=float)
    for i in range(len(d)):
        if has_prev[i] and np.isfinite(px[i]):
            k = fs.world_to_spline(px[i], py[i], pz[i], world.sp_pos)
            look[i] = [((sp_dir[la_idx[k, j]] - corr[i] + math.pi) % (2 * math.pi) - math.pi) / math.pi for j in range(de.N_LOOK)]
            minr[i] = min(2.0, 20.0 / max(la_minr[k], 1.0))
    # the plugin's NearestPointCorrector overrides the raw nearest point on a few percent of ticks,
    # and position is logged to 1 cm - so this one is a "most ticks agree" check
    rep.line('[7-11] spline turn ahead (x pi)', obs[:, 7:12].ravel(), look.ravel(), 0.02, 0.90)
    rep.line('[44] tightest radius ahead', obs[:, 44], minr, 0.02, 0.90)

    print("\n   What the two actions did:")
    after = d['SteerCommandDeg'].to_numpy(dtype=float)
    asked = max_steer * d['PolicySteerAction'].to_numpy(dtype=float)
    steer_rate = float((policy.meta.get('plugin_settings') or {}).get('MaxSteerRateDegS', 0.0))
    if steer_rate > 0.0:
        # the wheels move toward the asked angle by at most MaxSteerRateDegS x the tick's length
        # (from where they were: input 41; not on a car's first tick: input 45)
        step = steer_rate * d['RealDtMs'].to_numpy(dtype=float) / 1000.0
        before_tick = obs[:, 41] * max_steer
        limited = (obs[:, 45] < 0.5) & (np.abs(asked - before_tick) > step)
        expected = np.where(limited, np.clip(asked, before_tick - step, before_tick + step), asked)
        rep.line(f'steering = full lock x action, at most {steer_rate:g} deg/s', after, expected, 0.03, unit=' deg')
        print(f"        steering held back by the rate limit {limited.mean():.1%} of the time")
    else:
        rep.line('steering = full lock x action, deg', after, asked, 0.03, unit=' deg')
    scaled = d['CeilingKmh'] * 0.5 * (1.0 + d['PolicySpeedAction'])
    pedal_mode = bool((policy.meta.get('plugin_settings') or {}).get('EnableRearFrictionCircle'))
    if pedal_mode:
        # the speed output is a pedal: there is no target speed to move toward. The one-tick
        # replay (replay_live.py) is what checks the forward speed.
        pedal = d['PolicySpeedAction'].to_numpy(dtype=float)
        print(f"        pedal: throttle over 90% {np.mean(pedal > 0.9):.1%} of the time, under 10% either way "
              f"{np.mean(np.abs(pedal) < 0.1):.1%}, braking {np.mean(pedal <= -0.1):.1%}")
        if 'PolicyBrakeAction' in d.columns:
            brake = d['PolicyBrakeAction'].to_numpy(dtype=float)
            print(f"        brake with the throttle: {np.mean(brake >= 0.05):.1%} of the time, mean {np.nanmean(brake):.2f}"
                  f" (while on the throttle: {np.mean((brake >= 0.05) & (pedal > 0.1)):.1%})")
    elif 'OwnSpeedKmh' in d.columns:
        # own speed can only move toward the target the policy asked for
        own = d['OwnSpeedKmh'].to_numpy(dtype=float)
        own_prev = np.where(has_prev, p['OwnSpeedKmh'].to_numpy(dtype=float), nan)
        target = scaled.to_numpy(dtype=float)
        settings = policy.meta.get('plugin_settings') or {}
        if settings.get('EnableRearThrustLimit'):
            # with the rear thrust limit a sliding car can fall short of the target, or lose
            # speed while asking for more; what it cannot do is gain speed it did not ask for,
            # unless the limit also works the other way (EnableRearBrakeLimit)
            if settings.get('EnableRearBrakeLimit'):
                overshooting = np.nanmean((own_prev - target > 0.5) & (own > own_prev))
                print(f"        gaining speed while asking for less (brake-limited): {overshooting:.1%} of the time")
            else:
                gained = np.maximum((own - own_prev) - np.maximum(target - own_prev, 0.0), 0.0)
                rep.line('speed never rises past MaxSpeed x (1 + action) / 2', gained, np.zeros(len(d)), 1e-3)
            falling_short = np.nanmean((target - own_prev > 0.5) & (own < own_prev))
            print(f"        losing speed while asking for more (thrust-limited): {falling_short:.1%} of the time")
        else:
            toward = (own - own_prev) * (target - own_prev)
            rep.line('speed moves toward MaxSpeed x (1 + action) / 2', np.minimum(toward, 0.0), np.zeros(len(d)), 1e-3)
    print(f"        steering at full lock {np.mean(np.abs(after) > max_steer - 0.05):.1%} of the time"
          + ("" if pedal_mode else f"; target speed a median {np.median(scaled):.1f} km/h"))

    print("\n3. Server vs simulator, same policy")
    slip = d['RealSlipAngleDeg'].abs().to_numpy(dtype=float)
    track = de.track_surface_code(world)
    under = np.array([de.surface_under(world, x, y, z) for x, y, z in zip(d['PosX'], d['PosY'], d['PosZ'])])
    # the course (build_course.py): the same two measures drift_env scores, from the telemetry.
    # CrossTrackErrorM on row t was computed where the tick STARTED, i.e. at row t-1's position.
    n_points = len(world.sp_pos)
    margin = de.RewardConfig().course_margin_m
    overrun = np.zeros(len(d))
    on_straight = np.zeros(len(d), dtype=bool)
    hits, touching_before = 0, -1
    for i, (cte_i, x0, y0, z0, x1, z1, h1) in enumerate(zip(d['CrossTrackErrorM'], px, py, pz, d['PosX'], d['PosZ'],
                                                         np.radians(d['RealHeadingDeg'].to_numpy(dtype=float)))):
        if np.isfinite(x0):
            point = fs.world_to_spline(x0, y0, z0, world.sp_pos)
            overrun[i] = de.course_overrun_m(cte_i, point, margin, world.co, n_points)
            on_straight[i] = world.has_course and world.co[point, 6] > 0.5
        touching = de.marker_contact(x1, z1, h1, world.mk)
        hits += int(touching >= 0 and touching != touching_before)
        touching_before = touching
    run_minutes = float(d['RealDtMs'].sum()) / 60000.0
    rows = [
        ('time outside the course (markers)', float((overrun > 0).mean()), 'offcourse_fraction', '{:.1%}'),
        ('stacks / cones hit per minute', hits / max(run_minutes, 1e-9), 'marker_hits_per_min', '{:.1f}'),
        ('time with slip in 20-50 deg', float(((slip >= 20) & (slip <= 50)).mean()), 'drift_fraction', '{:.1%}'),
        ('time sliding (20-80 deg)', float(((slip >= de.SLIDE_MIN_DEG) & (slip <= de.SLIDE_MAX_DEG)).mean()), 'slide_fraction', '{:.1%}'),
        ('time at a high angle (40-80 deg)', float(((slip >= de.HIGH_ANGLE_MIN_DEG) & (slip <= de.SLIDE_MAX_DEG)).mean()), 'high_angle_fraction', '{:.1%}'),
        ('on the straight: time at 20+ deg', float((slip[on_straight] >= 20).mean()) if on_straight.any() else 0.0,
         'straight_drift_fraction', '{:.1%}'),
        ('mean |slip angle|, deg', float(np.nanmean(slip)), 'mean_abs_slip_deg', '{:.1f}'),
        ('time in wall contact (push-out)', float((d['CollisionPushOutM'] > 0).mean()), 'pushout_tick_fraction', '{:.2%}'),
        ('time off the paved surface', float((under != track).mean()), 'offroad_fraction', '{:.1%}'),
        ('time in spin / wrong-way recovery', float(d['UncontrolledSpinRecovering'].mean()), 'spin_recovery_fraction', '{:.2%}'),
        ('mean speed, km/h', float(d['SpeedKmh'].mean()), 'mean_speed_kmh', '{:.1f}'),
        ('mean distance from the line, m', float(d['CrossTrackErrorM'].abs().mean()), 'mean_abs_cte_m', '{:.1f}'),
    ]
    sim = None
    if simulate:
        # the same policy, the same number of ticks, this car's own speed limit, and no resets
        ceiling = float(np.nanmedian(d['CeilingKmh']))
        pace = float(np.nanmedian(d['Pace'])) if 'Pace' in d and de.pace_range(policy.meta)[1] > 0 else None
        cfg, never_reset = de.server_run_configs(policy.meta, ticks=len(d), ceiling_kmh=ceiling,
                                                 sliding_grip=sliding_grip, pace=pace,
                                                 skill=skill if lack > 0 else None)
        fs.PLUGIN_CONFIG_OVERRIDES.update(plugin_overrides_for(df))
        print(f"  (car height in this run: {'ground ray' if fs.PLUGIN_CONFIG_OVERRIDES['EXT_GROUND_RAY_HEIGHT'] else 'spline / road-mesh blend'})")
        print(f"  (simulating 128 runs of {len(d)} ticks without resets ...)", flush=True)
        sim = de.evaluate(world, policy, 128, seed=4242, env_config=cfg, reward_config=never_reset)
    print(f"  {'':34s}{'this server run':>16s}{'simulator median':>18s}{'middle 80% of runs':>22s}{'':3s}")
    unusual = 0
    for label, value, key, fmt in rows:
        if sim is None:
            print(f"  {label:34s}{fmt.format(value):>16s}")
            continue
        lo, med, hi = (float(np.percentile(sim[key], q)) for q in (10, 50, 90))
        outside = value < float(np.percentile(sim[key], 2)) or value > float(np.percentile(sim[key], 98))
        unusual += int(outside)
        print(f"  {label:34s}{fmt.format(value):>16s}{fmt.format(med):>18s}{(fmt.format(lo) + ' - ' + fmt.format(hi)):>22s}"
              f"{'  <-- outside 96% of simulator runs' if outside else ''}")
    respawns = int(df.groupby('SessionId')['SpawnCounter'].nunique().sum() - df['SessionId'].nunique())
    print(f"  {'re-teleports during the run':34s}{respawns:>16d}")
    if sim is not None:
        if unusual:
            print(f"  {unusual} measure(s) fall outside what the simulator produces for this policy. One unlucky run can do\n"
                  "  that, but it is also what a simulator/plugin mismatch looks like: run replay_live.py on this file.")
        else:
            print("  The server run is within the range the simulator produces for this policy.")

    print(f"\n{'ALL CHECKS PASSED' if rep.failed == 0 else str(rep.failed) + ' CHECK(S) FAILED - send this output back'}")
    return 0 if rep.failed == 0 else 1


def synthetic_telemetry(world, policy, de, fs, path, n_ticks=1500, seed=3):
    """Telemetry in the plugin's own column names and number formats, generated by the simulator
    driving with the policy - what a correct C# port should produce. Used by --self-test."""
    # one RearSlidingGrip for the whole file, as on the server: the middle of the trained range
    grip_low, grip_high = de.sliding_grip_range(policy.meta)
    grip = round(0.5 * (grip_low + grip_high), 2)
    env_cfg = de.env_config_for(policy.meta, episode_ticks=10 ** 9,
                                rear_sliding_grip_low=grip, rear_sliding_grip_high=grip)
    env = de.DriftVecEnv(world, 1, env_cfg, seed=seed)
    obs = env.reset()
    cols = ['Tick', 'SessionId', 'PosX', 'PosY', 'PosZ', 'SpeedKmh', 'CeilingKmh', 'CorrectedSplineAngle', 'RayDistances',
            'FanCenterDeg', 'PinDistances', 'SpawnCounter', 'RealDtMs',
            'RealHeadingDeg', 'YawRateDegS', 'LateralVelocityMs', 'SteerCommandDeg', 'RealSlipAngleDeg', 'CrossTrackErrorM',
            'CollisionPushOutM', 'UncontrolledSpinRecovering', 'PolicyActive', 'PolicySteerAction', 'PolicySpeedAction',
            'PolicyObs', 'GroundRayUsed', 'GroundRayY', 'PolicyBrakeAction', 'Pace', 'NearestPointId', 'PaceOver']
    spawn = 0
    ground_ray = bool(env.params[0, fs.P['EXT_GROUND_RAY_HEIGHT']] > 0.5)
    with open(path, 'w') as f:
        f.write(','.join(cols) + '\n')
        for tick in range(1, n_ticks + 1):
            o = obs[0].copy()
            dt = env.mids[0, fs.M_DT]
            a = policy(o)[0]
            prev_latv = env.states[0, fs.S_LATV]
            pace = env.states[0, fs.S_PACE]         # the pace this tick is driven at (it may be redrawn after)
            obs, r, term, trunc, info = env.step(a[None, :])
            dg = env.diags[0]
            if term[0] or trunc[0]:
                spawn += 1          # the car was reset: this tick's state row is already the new car's
                continue
            s = env.states[0]
            speed = math.hypot(dg[fs.D_BodyForwardSpeedMs], s[fs.S_LATV]) * 3.6
            row = [tick, 16, f"{s[fs.S_X]:.2f}", f"{s[fs.S_Y]:.2f}", f"{s[fs.S_Z]:.2f}", f"{speed:.1f}",
                   f"{s[fs.S_MAX_SPEED] * 3.6:.1f}", f"{dg[fs.D_RawSplineAngle]:.4f}",
                   ';'.join(f"{v:.1f}" for v in s[fs.S_RAY0:fs.S_RAY0 + fs.N_RAYS]),
                   f"{math.degrees(s[fs.S_FAN_CENTER]):.1f}",
                   ';'.join(f"{v:.1f}" for v in s[fs.S_PIN0:fs.S_PIN0 + fs.N_PINS]),
                   spawn, f"{dt * 1000:.1f}",
                   f"{math.degrees(s[fs.S_HEADING]):.2f}", f"{math.degrees(s[fs.S_YAW]):.2f}", f"{s[fs.S_LATV]:.3f}",
                   f"{dg[fs.D_SteerCommandDeg]:.2f}", f"{math.degrees(dg[fs.D_RealSlipAngleRad]):.2f}",
                   f"{dg[fs.D_CrossTrackErrorM]:.3f}", f"{dg[fs.D_CollisionPushOutM]:.3f}",
                   bool(dg[fs.D_UncontrolledSpinRecovering] > 0.5), True, f"{a[0]:.4f}", f"{a[1]:.4f}",
                   ';'.join(f"{v:.4f}" for v in o),
                   ground_ray, f"{(s[fs.S_Y] - env.params[0, fs.P['GROUND_RAY_HEIGHT_OFFSET_M']]) if ground_ray else 0.0:.3f}",
                   f"{(min(1.0, max(0.0, a[2])) if len(a) > 2 else 0.0):.4f}", f"{pace:.4f}",
                   int(dg[fs.D_NearestPointId]), f"{o[de.PACE_OVER_SLOT]:.4f}"]
            f.write(','.join(str(v) for v in row) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('telemetry', nargs='?')
    ap.add_argument('--policy', default=None,
                    help='the policy file the server ran. Default: the one the plugin is built with '
                         '(GradientDriftPlugin/GradientDriftPlugin.policy.json)')
    tf.tracks_arg(ap)
    ap.add_argument('--track', default=None,
                    help="the track the server ran (its folder name under content/tracks/). Default: the "
                         "policy's own track; give it for a run on another track")
    ap.add_argument('--self-test', action='store_true')
    ap.add_argument('--no-sim', action='store_true', help='skip the simulator comparison in part 3')
    args = ap.parse_args()
    sys.path.insert(0, _HERE)
    import fast_sim as fs
    import drift_env as de
    from policy import Policy, default_policy_path, warn_if_old_simulator

    if args.policy is None:
        args.policy = default_policy_path()
    print(f"policy: {os.path.abspath(args.policy)}")
    policy = Policy.load_json(args.policy)
    warn_if_old_simulator(policy, fs.SIMULATOR_REVISION, args.policy)
    track = args.track or policy.meta.get('track') or tf.TRACK
    print(f"track: {track}")
    world = fs.load_world(args.tracks, track=track)
    if len(policy.obs_mean) > de.PACE_OVER_SLOT:
        try:
            world.pace_ref = de.course_pace_reference(args.tracks, track, world)
        except RuntimeError as e:
            print(f"({e})")
    if args.self_test:
        import tempfile
        path = os.path.join(tempfile.gettempdir(), 'synthetic_policy_telemetry.csv')
        synthetic_telemetry(world, policy, de, fs, path)
        print(f"self-test: checking simulator-generated telemetry ({path})")
        return run_checks(load_telemetry(path), policy, world, de, fs, simulate=not args.no_sim)
    if not args.telemetry:
        ap.error("give the telemetry CSV, or --self-test")
    return run_checks(load_telemetry(args.telemetry), policy, world, de, fs, simulate=not args.no_sim)


if __name__ == '__main__':
    sys.exit(main())
